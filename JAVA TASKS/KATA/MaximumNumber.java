

public class MaximumNumber{

	public static int max(int numberOne, int numberTwo){
	
	if (numberOne > numberTwo ){
	return numberOne;
	}
	
	else{
	return numberTwo;
	
	}


	}
	public static void main(String[]args){
	int result = max(15,27);

	System.out.println("The maximum is:  " + result);

}









}


